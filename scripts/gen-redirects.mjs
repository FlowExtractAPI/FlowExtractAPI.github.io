// gen-redirects.mjs: writes public/_redirects (Cloudflare Workers static assets) from URLS.md rules.
// html_handling is "none", so folder indexes are served by 200 rewrites, and every old Jekyll/extensionless
// address gets a 301 to the canonical /docs/<slug>.html page. Static rules only (limit 2,000).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const actors = fs.readdirSync(path.join(ROOT, 'content/actors')).filter((f) => f.endsWith('.json')).map((f) => f.replace(/\.json$/, ''));
const lines = [
  '# Generated by scripts/gen-redirects.mjs. Do not edit by hand.',
  '# Folder indexes (html_handling "none" serves only exact file paths)',
  '/ /index.html 200',
  '/index.html / 301',
  '/simple-merge/ /simple-merge/index.html 200',
  '/zoom-downloader/ /zoom-downloader/index.html 200',
  '/simple-merge /simple-merge/ 301',
  '/zoom-downloader /zoom-downloader/ 301',
  '/simple-merge/privacy /simple-merge/privacy.html 301',
  '/simple-merge/terms /simple-merge/terms.html 301',
  '/docs/ /#actors 301',
  '/docs /#actors 301',
  '/docs/actors/ /#actors 301',
  '# Old copies of every actor page (Jekyll extras + extensionless) -> canonical page',
];
for (const s of actors.sort()) {
  lines.push(`/docs/${s} /docs/${s}.html 301`);
  lines.push(`/docs/actors/${s}.md /docs/${s}.html 301`);
  lines.push(`/docs/actors/${s}.html /docs/${s}.html 301`);
  lines.push(`/docs/actors/${s} /docs/${s}.html 301`);
}
// Old URLs whose letter case differs from the page (Store slug Youtube-Scraper-Pro)
for (const [from, to] of [['/docs/Youtube-Scraper-Pro.html', '/docs/youtube-scraper-pro.html'], ['/docs/actors/Youtube-Scraper-Pro.md', '/docs/youtube-scraper-pro.html']]) lines.push(`${from} ${to} 301`);
fs.writeFileSync(path.join(ROOT, 'public/_redirects'), lines.join('\n') + '\n');
console.log(`_redirects: ${lines.filter((l) => !l.startsWith('#')).length} rules`);
